const academicYearData = {
  "2025-2026": facultyConferences_2025_26,
  "2024-2025": facultyConferences_2024_25,
};

let activeYear = "All Years";
let sortCol = null;
let sortDir = 1;

function val(v) {
  return v && String(v).trim() ? String(v).trim() : "—";
}

function linkBtn(url, label, type) {
  if (!url) return "";

  const icon =
    type === "doi"
      ? "file-lines"
      : type === "scopus"
        ? "graduation-cap"
        : "external-link-alt";

  return `<a href="${url}" target="_blank" rel="noopener"
  class="link-btn link-${type}">
  <i class="fas fa-${icon}"></i> ${label}</a>`;
}

function profileLinks(links) {
  if (!links) return '<span style="color:#bbb;font-size:0.75rem;">N/A</span>';

  let html = "";

  if (links.Scopus || links.scopus) {
    html += linkBtn(links.Scopus || links.scopus, "Scopus", "scopus") + "<br>";
  }

  if (links.wos) {
    html += linkBtn(links.wos, "WoS", "wos") + "<br>";
  }

  if (links.Springer) {
    html += linkBtn(links.Springer, "springer", "springer") + "<br>";
  }

  return html || '<span style="color:#bbb;font-size:0.75rem;">N/A</span>';
}

function updateStats() {
  const all = Object.values(academicYearData).flat();

  const authors = new Set(
    all.map((p) => p.authors.split(/[,;]/)[0].trim().toUpperCase()),
  );

  document.getElementById("statTotal").textContent = all.length;

  document.getElementById("statYears").textContent =
    Object.keys(academicYearData).length;

  document.getElementById("statScopus").textContent = all.filter((p) =>
    p.indexing.toLowerCase().includes("scopus"),
  ).length;

  document.getElementById("statAuthors").textContent = authors.size;
}

function buildYearFilter() {
  const select = document.getElementById("filterYear");

  select.innerHTML = "";

  const allOpt = document.createElement("option");
  allOpt.value = "All Years";
  allOpt.textContent = "All Years";

  select.appendChild(allOpt);

  Object.keys(academicYearData).forEach((year) => {
    const opt = document.createElement("option");

    opt.value = year;
    opt.textContent = `${year} (${academicYearData[year].length})`;

    select.appendChild(opt);
  });

  select.addEventListener("change", () => {
    activeYear = select.value;
    render();
  });
}

function getActiveData() {
  if (activeYear === "All Years") {
    return Object.values(academicYearData).flat();
  }

  return academicYearData[activeYear] || [];
}

function render() {
  const search = document.getElementById("searchInput").value.toLowerCase();

  const idxFilt = document.getElementById("filterIndexing").value;

  let data = [...getActiveData()];

  if (sortCol) {
    data.sort((a, b) => {
      if (sortCol === "monthYear") {
        const parseDate = (d) => {
          if (!d) return 0;
          const months = [
            "January",
            "February",
            "March",
            "April",
            "May",
            "June",
            "July",
            "August",
            "September",
            "October",
            "November",
            "December",
          ];
          const match = String(d).match(/(\w+)\s+(\d{4})/);
          if (!match) return 0;
          const monthIdx = months.findIndex((m) => match[1].includes(m));
          return parseInt(match[2]) * 12 + monthIdx;
        };
        return (
          (parseDate(a.conferenceDates) - parseDate(b.conferenceDates)) *
          sortDir
        );
      }
      return (
        String(a[sortCol] || "").localeCompare(String(b[sortCol] || "")) *
        sortDir
      );
    });
  }

  const tbody = document.getElementById("tableBody");

  tbody.innerHTML = "";

  let visible = 0;

  data.forEach((p, i) => {
    const searchable = [
      p.authors,
      p.title,
      p.conferenceName,
      p.isbn,
      p.conferenceDates,
    ]
      .join(" ")
      .toLowerCase();

    if (search && !searchable.includes(search)) return;

    if (idxFilt && p.indexing !== idxFilt) return;

    visible++;

    const tr = document.createElement("tr");

    tr.innerHTML = `
<td>${visible}</td>
<td>${val(p.authors)}</td>
<td>${val(p.title)}</td>
<td>${val(p.conferenceName)}</td>
<td>${val(p.isbn)}</td>


<td>${val(p.pages)}</td>
<td>${val(p.conferenceDates)}</td>
<td><span class="badge-index">${val(p.indexing)}</span></td>
<td>${linkBtn(p.paperLink, "Paper", "doi")}</td>
<td>${profileLinks(p.profileLinks)}</td>
`;

    tbody.appendChild(tr);
  });

  const total = getActiveData().length;

  document.getElementById("resultCount").textContent =
    `Showing ${visible} of ${total} records`;

  document.getElementById("noResults").classList.toggle("d-none", visible > 0);
}

document.querySelectorAll("thead th[data-col]").forEach((th) => {
  th.addEventListener("click", () => {
    const col = th.dataset.col;

    sortDir = sortCol === col ? sortDir * -1 : 1;

    sortCol = col;

    render();
  });
});

document.getElementById("searchInput").addEventListener("input", render);

document.getElementById("filterIndexing").addEventListener("change", render);

updateStats();

buildYearFilter();

render();
